#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Extracts the per-request failure attribution from k6's `--out json` sample
// streams into one small committed artifact.
//
//   node benchmarks/scripts/attribute-failures.mjs
//
// Why this exists: the summary export carries only aggregates, so a run with a
// high `http_req_failed` rate cannot be explained from it — "failed" could be a
// server error, a reset, or the client giving up, and those have opposite fixes.
// k6 records an `error_code` per request in the json output, but those streams
// are ~10 MB per matrix and are gitignored. This distils them to a few KB of
// evidence that CAN be committed alongside the numbers they explain.
//
// k6 error codes seen in v0 (docs: grafana.com/docs/k6/latest/javascript-api/error-codes):
//   1050 — request timeout (the CLIENT stopped waiting)
//   1220 — read: connection reset by peer (the SERVER sent an RST)
// ---------------------------------------------------------------------------
import { readdirSync, existsSync, createReadStream, writeFileSync } from 'node:fs';
import { createGunzip } from 'node:zlib';
import { createInterface } from 'node:readline';
import { join } from 'node:path';

const DIR = 'benchmarks/v0-baseline/results';
const OUT = 'benchmarks/v0-baseline/failure-attribution.txt';

const CODE_NAMES = {
  1050: 'request timeout (client stopped waiting)',
  1220: 'connection reset by peer (server sent RST)',
  1211: 'connection refused',
  1000: 'generic error',
};

if (!existsSync(DIR)) {
  console.error(`no results directory: ${DIR}`);
  process.exit(1);
}

const files = readdirSync(DIR)
  .filter((f) => f.endsWith('.samples.json.gz'))
  .sort();

if (files.length === 0) {
  console.error(`no *.samples.json.gz in ${DIR}`);
  console.error('these are written by `k6 run --out json=…` in run-baseline.sh and are gitignored;');
  console.error('re-run the matrix if you need to regenerate this artifact.');
  process.exit(1);
}

const quantile = (sorted, q) => sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * q))];

const rows = [];
for (const f of files) {
  const byCode = new Map();
  let total = 0;

  const rl = createInterface({
    input: createReadStream(join(DIR, f)).pipe(createGunzip()),
    crlfDelay: Infinity,
  });

  for await (const line of rl) {
    // Cheap prefilter: the stream is mostly other metrics.
    if (!line.includes('"http_req_duration"')) continue;
    let d;
    try {
      d = JSON.parse(line);
    } catch {
      continue;
    }
    if (d.metric !== 'http_req_duration' || d.type !== 'Point') continue;
    total += 1;
    const tags = d.data.tags || {};
    const code = tags.error_code ? String(tags.error_code) : 'ok';
    if (!byCode.has(code)) byCode.set(code, { n: 0, msg: tags.error || '', ms: [] });
    const e = byCode.get(code);
    e.n += 1;
    e.ms.push(d.data.value);
    if (!e.msg && tags.error) e.msg = tags.error;
  }

  rows.push({ run: f.replace('.samples.json.gz', ''), total, byCode });
  console.error(`  read ${f} (${total} requests)`);
}

const lines = [];
lines.push('v0 baseline — per-request failure attribution');
lines.push('');
lines.push('Generated by benchmarks/scripts/attribute-failures.mjs from the k6 --out json');
lines.push('sample streams. Those streams are gitignored (~10 MB); this is the distilled');
lines.push('evidence. Regenerate by re-running the matrix, then re-running the script.');
lines.push('');
lines.push('error_code meanings (k6): 1050 = request timeout, the client stopped waiting.');
lines.push('1220 = read: connection reset by peer, i.e. the RST came from the server side,');
lines.push('so the request was never answered rather than answered with an error.');
lines.push('');
lines.push(
  ['run', 'requests', 'code', 'n', 'share', 'min ms', 'med ms', 'max ms', 'message'].join('\t')
);
for (const r of rows) {
  const codes = [...r.byCode.entries()].sort((a, b) => b[1].n - a[1].n);
  for (const [code, e] of codes) {
    e.ms.sort((a, b) => a - b);
    lines.push(
      [
        r.run,
        r.total,
        code === 'ok' ? 'ok' : `${code} ${CODE_NAMES[code] ? '' : '(unknown)'}`.trim(),
        e.n,
        ((100 * e.n) / r.total).toFixed(2) + '%',
        e.ms[0].toFixed(0),
        quantile(e.ms, 0.5).toFixed(0),
        e.ms[e.ms.length - 1].toFixed(0),
        e.msg || (code === 'ok' ? '—' : ''),
      ].join('\t')
    );
  }
}
lines.push('');

writeFileSync(OUT, lines.join('\n'));
console.error(`\n[attribute-failures] wrote ${OUT} from ${files.length} sample stream(s)`);
